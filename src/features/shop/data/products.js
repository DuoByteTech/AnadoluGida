const toSlug = (str = "") =>
  str
    .toLowerCase()
    .trim()
    .replace(/ä/g, "ae")
    .replace(/ö/g, "oe")
    .replace(/ü/g, "ue")
    .replace(/ß/g, "ss")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const round2 = (n) => Math.round((n + Number.EPSILON) * 100) / 100;

export const products = rawProducts.map((p) => {
  const images = Array.isArray(p.images) ? p.images : [];
  const gallery = (images.length ? images : [p.image]).filter(Boolean);

  // ✅ indirimli ürünlerde oldPrice hesapla (yoksa)
  let oldPrice = p.oldPrice;
  if (p.isDiscounted) {
    const pct = typeof p.discountPercent === "number" ? p.discountPercent : 20; // default %20
    if (typeof oldPrice !== "number") {
      oldPrice = round2(p.price / (1 - pct / 100));
    }
  } else {
    oldPrice = undefined; // indirim yoksa temiz tutalım
  }

  return {
    ...p,
    images: gallery,
    oldPrice,
    slug: toSlug(p.name),
  };
});
